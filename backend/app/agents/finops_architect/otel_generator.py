"""
OpenTelemetry Collector Configuration Generator.
Produces valid, production-grade OpenTelemetry Collector YAML for dual-shipping and vendor-neutral ingestion.
"""

import yaml


class OTelCollectorGenerator:
    @classmethod
    def generate_collector_yaml(
        cls,
        company_name: str,
        target_backend: str = "SigNoz",
        enable_dual_shipping: bool = True,
    ) -> str:
        """Generates validated OpenTelemetry Collector YAML with dual-shipping pipelines."""
        exporters_dict = {
            "otlp/signoz": {
                "endpoint": "ingest.us.signoz.cloud:443",
                "headers": {
                    "signoz-access-token": "${SIGNOZ_INGESTION_KEY}"
                },
                "tls": {
                    "insecure": False
                }
            }
        }
        
        trace_exporters = ["otlp/signoz"]
        metric_exporters = ["otlp/signoz"]
        log_exporters = ["otlp/signoz"]

        if enable_dual_shipping:
            exporters_dict["datadog"] = {
                "api": {
                    "key": "${DD_API_KEY}",
                    "site": "datadoghq.com"
                }
            }
            trace_exporters.append("datadog")
            metric_exporters.append("datadog")
            log_exporters.append("datadog")

        config = {
            "receivers": {
                "otlp": {
                    "protocols": {
                        "grpc": {"endpoint": "0.0.0.0:4317"},
                        "http": {"endpoint": "0.0.0.0:4318"}
                    }
                },
                "datadog": {
                    "endpoint": "0.0.0.0:8126",
                    "read_timeout": "60s"
                }
            },
            "processors": {
                "memory_limiter": {
                    "check_interval": "1s",
                    "limit_percentage": 75,
                    "spike_limit_percentage": 20
                },
                "batch": {
                    "send_batch_size": 10000,
                    "timeout": "5s"
                },
                "resourcedetection": {
                    "detectors": ["env", "system"],
                    "timeout": "2s"
                }
            },
            "exporters": exporters_dict,
            "extensions": {
                "health_check": {
                    "endpoint": "0.0.0.0:13133"
                }
            },
            "service": {
                "extensions": ["health_check"],
                "pipelines": {
                    "traces": {
                        "receivers": ["otlp", "datadog"],
                        "processors": ["memory_limiter", "resourcedetection", "batch"],
                        "exporters": trace_exporters
                    },
                    "metrics": {
                        "receivers": ["otlp"],
                        "processors": ["memory_limiter", "batch"],
                        "exporters": metric_exporters
                    },
                    "logs": {
                        "receivers": ["otlp"],
                        "processors": ["memory_limiter", "batch"],
                        "exporters": log_exporters
                    }
                },
                "telemetry": {
                    "logs": {
                        "level": "info"
                    }
                }
            }
        }

        # Dump to clean formatted YAML with banner header
        yaml_body = yaml.dump(config, sort_keys=False, default_flow_style=False)
        header = (
            f"# ==============================================================================\n"
            f"# OpenTelemetry Collector Configuration Blueprint for {company_name}\n"
            f"# Target: {target_backend} | Dual-Shipping: {enable_dual_shipping}\n"
            f"# Generated by The Churn Poacher (Architecture Migration Agent)\n"
            f"# ==============================================================================\n\n"
        )
        return header + yaml_body

    @classmethod
    def validate_yaml(cls, yaml_content: str) -> bool:
        """Validates that the generated YAML string is syntactically sound."""
        try:
            parsed = yaml.safe_load(yaml_content)
            return isinstance(parsed, dict) and "receivers" in parsed and "service" in parsed
        except Exception:
            return False
